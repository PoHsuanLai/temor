#!/bin/sh
# Regenerate src/bindings.rs from the pinned Ghostty headers. Run after bumping the pin; build.rs
# never runs bindgen.
#
#   GHOSTTY_SOURCE_DIR=<ghostty tree at the pinned commit> scripts/gen-bindings.sh
#
# Needs libclang. Build output goes to $CARGO_TARGET_DIR (set it outside $HOME).
set -eu
here=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
: "${GHOSTTY_SOURCE_DIR:?set GHOSTTY_SOURCE_DIR to the pinned Ghostty tree (scripts/fetch-ghostty.sh)}"
want=$(sed -n 's/^pub const GHOSTTY_COMMIT: &str = "\([0-9a-f]*\)";/\1/p' "$here/src/lib.rs")
have=$(git -C "$GHOSTTY_SOURCE_DIR" rev-parse HEAD)
if [ "$want" != "$have" ]; then
  echo "GHOSTTY_SOURCE_DIR is at $have but src/lib.rs pins $want; update GHOSTTY_COMMIT first" >&2
  exit 1
fi
out="$here/src/bindings.rs"
cargo run --quiet --manifest-path "$here/tools/gen-bindings/Cargo.toml" -- \
  "$GHOSTTY_SOURCE_DIR/include" "$out.tmp"
{
  echo "// Generated by scripts/gen-bindings.sh from Ghostty $have include/ghostty/vt.h."
  echo "// Do not edit by hand."
  echo
  cat "$out.tmp"
} > "$out"
rm -f "$out.tmp"
echo "wrote $out"
