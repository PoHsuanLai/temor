#!/bin/sh
# Writes src/proposal/ucd_tables.rs from the Unicode Character Database: the
# Default_Ignorable_Code_Point ranges (DerivedCoreProperties.txt) and the Zs space separators
# (extracted/DerivedGeneralCategory.txt) that sanitising removes or maps to a plain space.
#
# Usage: scripts/gen-ignorable.sh [UCD directory]   (default /usr/share/unicode/ucd)
# Run from crates/temor-blocks. Re-run when the UCD version moves, and commit the table.
set -eu
ucd="${1:-/usr/share/unicode/ucd}"
out="src/proposal/ucd_tables.rs"
core="$ucd/DerivedCoreProperties.txt"
category="$ucd/extracted/DerivedGeneralCategory.txt"
version=$(head -1 "$core" | sed -n 's/^# DerivedCoreProperties-\(.*\)\.txt$/\1/p')
[ -n "$version" ] || { echo "cannot read the UCD version from $core" >&2; exit 1; }

# `ranges FILE PROPERTY` prints `    (0xFIRST, 0xLAST),` for every line whose property is PROPERTY.
ranges() {
    sed -e 's/#.*//' "$1" | awk -F';' -v want="$2" '
        { gsub(/ /, "", $1); gsub(/ /, "", $2) }
        $2 == want {
            n = split($1, r, /\.\./)
            first = r[1]; last = (n == 2) ? r[2] : r[1]
            printf "    (0x%s, 0x%s),\n", first, last
        }'
}

{
    echo "//! Generated by \`scripts/gen-ignorable.sh\` from the Unicode Character Database $version."
    echo "//! Do not edit; re-run the script."
    echo
    echo "/// The UCD version these tables come from."
    echo "pub const UCD_VERSION: &str = \"$version\";"
    echo
    echo "/// Default_Ignorable_Code_Point: characters that draw nothing, as inclusive ranges in the file's order."
    echo "pub(super) const DEFAULT_IGNORABLE: &[(u32, u32)] = &["
    ranges "$core" Default_Ignorable_Code_Point
    echo "];"
    echo
    echo "/// General_Category=Zs: space separators, as inclusive ranges in the file's order."
    echo "pub(super) const SPACE_SEPARATORS: &[(u32, u32)] = &["
    ranges "$category" Zs
    echo "];"
} > "$out"
echo "wrote $out from UCD $version"
